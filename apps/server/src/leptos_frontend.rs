//! Leptos frontend serving.
//!
//! Serves the Trunk-built SPA (index.html + WASM bundle + CSS) and
//! falls back to index.html for client-side routing.

use axum::extract::Request;
use axum::http::{HeaderMap, StatusCode};
use axum::response::{Html, IntoResponse, Redirect, Response};
use tower::ServiceExt;
use tower_http::services::ServeDir;

/// Path to Trunk dist directory (relative to where the binary runs).
/// Set via TRUNK_DIST_DIR env var, or defaults to crates/krausen-ui/dist.
fn dist_dir() -> String {
    std::env::var("TRUNK_DIST_DIR").unwrap_or_else(|_| "crates/krausen-ui/dist".to_string())
}

/// Build a ServeDir service for static assets from trunk dist.
pub fn static_files_service() -> ServeDir {
    ServeDir::new(dist_dir())
}

/// The shell is always revalidated: `no-cache` means "cache it, but revalidate
/// every time" (not "don't cache"), so a new build is picked up at once.
fn no_cache(mut response: Response) -> Response {
    response.headers_mut().insert(
        axum::http::header::CACHE_CONTROL,
        axum::http::HeaderValue::from_static("no-cache"),
    );
    response
}

/// Serve the SPA index.html from trunk dist (fallback for all routes).
pub async fn serve() -> Response {
    let index_path = format!("{}/index.html", dist_dir());
    match tokio::fs::read_to_string(&index_path).await {
        Ok(html) => no_cache(Html(html).into_response()),
        Err(_) => (
            StatusCode::NOT_FOUND,
            "Frontend not built. Run: cd crates/krausen-ui && trunk build",
        )
            .into_response(),
    }
}

/// Wrap a server-rendered auth component in the stylesheet generated by
/// Trunk. This document has no client script: the consent forms work without
/// hydration, and the browser displays the exact view reviewed by the user.
pub async fn consent_document(body: &str) -> String {
    scriptless_auth_document("Allow MCP access · Krausen", body).await
}

/// Shared scriptless auth shell. Titles are trusted static copy, never request
/// values; callers render and escape dynamic body content with Leptos.
pub async fn scriptless_auth_document(title: &'static str, body: &str) -> String {
    let stylesheet = tokio::fs::read_to_string(format!("{}/index.html", dist_dir()))
        .await
        .ok()
        .and_then(|html| {
            html.lines()
                .find(|line| {
                    line.contains(r#"rel="stylesheet""#) && line.contains(r#"href="/output-"#)
                })
                .map(str::trim)
                .map(str::to_owned)
        })
        .unwrap_or_default();
    format!(
        r#"<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="referrer" content="no-referrer"><title>{title}</title><link rel="icon" href="/public/krausen_small_logo.svg">{stylesheet}</head><body>{body}</body></html>"#
    )
}

/// Serve the Leptos shell HTML (for explicit /login, /signup routes).
pub async fn serve_leptos_shell() -> Response {
    serve().await
}

/// Check for auth cookies and redirect to `/login?redirect=<path>` if none present.
///
/// Serves the page if either the access OR the refresh token cookie is
/// present. When only the refresh cookie exists (access token expired), the
/// pre-boot refresh script in index.html exchanges it for a new access token
/// before WASM boots.
///
/// The redirect path is validated to contain only safe characters
/// (alphanumeric, `/`, `-`, `_`) to prevent query-param injection or
/// open-redirect attacks.
fn check_auth_cookie_or_redirect(
    headers: &HeaderMap,
    uri: Option<&axum::http::Uri>,
) -> Option<Response> {
    let cookies_str = headers
        .get("cookie")
        .and_then(|v| v.to_str().ok())
        .unwrap_or("");

    let has_cookie = |name: &str| {
        let prefix = format!("{name}=");
        cookies_str.split(';').any(|c| {
            let c = c.trim();
            c.starts_with(&prefix) && c.len() > prefix.len()
        })
    };

    let access_name = &krausen_core::constants::get().cookies.access_token_name;
    let refresh_name = &krausen_core::constants::get().cookies.refresh_token_name;

    if has_cookie(access_name) || has_cookie(refresh_name) {
        return None;
    }

    // Build redirect URL, validating the path contains only safe characters
    let redirect_path = uri.map(|u| u.path().to_string()).unwrap_or_default();
    if redirect_path.is_empty()
        || redirect_path == "/"
        || redirect_path == "/login"
        || !redirect_path
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'/' || b == b'-' || b == b'_')
    {
        return Some(Redirect::to("/login").into_response());
    }
    Some(Redirect::to(&format!("/login?redirect={redirect_path}")).into_response())
}

/// Whether `path` (stripped of its leading `/`) is a public page route: one
/// that must render without an auth cookie.
///
/// `path` is matched, never a full URL, so the `starts_with` prefixes below
/// only ever match the route segment itself.
fn is_public_route(path: &str) -> bool {
    matches!(
        path,
        "login" | "signup" | "welcome" | "unsubscribe" | "oauth-complete"
    ) || path.starts_with("signup/")
        || path.starts_with("auth/")
        || path.starts_with("account/")
}

/// Whether a request that matched no file should get the SPA shell.
///
/// The server cannot know which paths the client-side router owns, so it has
/// to guess — and guessing wrong in either direction costs something. Answer
/// the shell too readily and a missing image or script returns HTML with a 200,
/// which hides broken references and makes a typo look like a working page.
/// Answer 404 too readily and real pages report themselves as missing to
/// monitoring, caches and crawlers, which is the bug this whole fallback exists
/// to fix.
///
/// Two signals, either of which is enough:
///
/// - The request accepts HTML. Browsers navigating to a page send
///   `text/html` in `Accept`; a `<script>`, `<img>` or `fetch` for an asset
///   does not. This is the reliable signal when it is present.
/// - The last path segment has no extension. `Accept` is often `*/*` — curl
///   and most uptime checks send exactly that — so extension is what keeps
///   `/settings/profile` a page when nothing states a preference, while
///   `/favicon.ico` and `/app.js` stay missing files.
///
/// A path segment containing a dot is therefore read as a filename, so a route
/// like `/users/jason.smith` relies on the `Accept` signal — which a browser
/// navigating there does send.
fn wants_shell(path: &str, accept: Option<&str>) -> bool {
    if accept.is_some_and(|a| a.contains("text/html")) {
        return true;
    }

    let last_segment = path.rsplit('/').next().unwrap_or_default();
    !last_segment.contains('.')
}

/// Serve a static asset if one matches, otherwise the SPA shell.
///
/// `ServeDir::not_found_service` cannot be used for this: it returns the
/// fallback's body but forces the status to 404, so every client-side route
/// answered "not found" while rendering perfectly. A URL the router handles
/// is a real page and has to say 200 — monitoring, caches and crawlers all
/// read the status rather than the body.
///
/// A request that matches no file and is not a page keeps its 404; see
/// [`wants_shell`].
pub async fn serve_asset_or_shell(request: Request) -> Response {
    let path = request.uri().path().to_string();
    let accept = request
        .headers()
        .get(axum::http::header::ACCEPT)
        .and_then(|v| v.to_str().ok())
        .map(str::to_string);
    let headers = request.headers().clone();
    let uri = request.uri().clone();

    // The shell is rendered by `serve()` (no validators, always a full 200):
    // a conditional or range request answered from the dist directory would
    // return a bodiless 304 that pairs the browser's cached shell, stamped with
    // an old CSP nonce, with a fresh nonce in the response header.
    if path == "/" || path == "/index.html" {
        return serve().await;
    }

    let response = static_files_service()
        .oneshot(request)
        .await
        .map(IntoResponse::into_response);

    match response {
        Ok(response) if response.status() != StatusCode::NOT_FOUND => response,
        // No such file. A page is handed to the client-side router; anything
        // that reads as a missing asset stays missing.
        _ if wants_shell(&path, accept.as_deref()) => {
            // Protected pages need a session cookie; public pages pass through.
            if !is_public_route(path.trim_start_matches('/'))
                && let Some(redirect) = check_auth_cookie_or_redirect(&headers, Some(&uri))
            {
                return redirect;
            }
            serve().await
        }
        Ok(response) => response,
        Err(_) => StatusCode::NOT_FOUND.into_response(),
    }
}

#[cfg(test)]
mod tests {
    use super::{check_auth_cookie_or_redirect, is_public_route, wants_shell};

    const BROWSER: Option<&str> =
        Some("text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8");
    const ASSET: Option<&str> = Some("image/avif,image/webp,*/*");
    const ANYTHING: Option<&str> = Some("*/*");

    #[test]
    fn a_page_a_browser_navigated_to_gets_the_shell() {
        assert!(wants_shell("/settings/profile", BROWSER));
        assert!(wants_shell("/recipes", BROWSER));
        assert!(wants_shell("/", BROWSER));
    }

    #[test]
    fn a_missing_asset_stays_missing() {
        assert!(!wants_shell("/favicon.ico", ASSET));
        assert!(!wants_shell("/app.js", ANYTHING));
        assert!(!wants_shell("/style.css", None));
        assert!(!wants_shell("/bundle.wasm", ANYTHING));
        assert!(!wants_shell("/main.js.map", ANYTHING));
    }

    /// curl and most uptime checks send `*/*`, and they are exactly the
    /// callers this fallback exists for — a page must not read as missing to
    /// them just because they stated no preference.
    #[test]
    fn a_page_is_still_a_page_without_an_accept_preference() {
        assert!(wants_shell("/settings/profile", ANYTHING));
        assert!(wants_shell("/settings/profile", None));
    }

    /// A dotted segment reads as a filename, so this one leans on Accept.
    #[test]
    fn a_route_that_looks_like_a_filename_needs_the_accept_signal() {
        assert!(wants_shell("/users/jason.smith", BROWSER));
        assert!(!wants_shell("/users/jason.smith", ANYTHING));
    }

    #[test]
    fn a_dot_earlier_in_the_path_does_not_make_it_an_asset() {
        assert!(wants_shell("/v1.2/settings", ANYTHING));
    }

    // ─── signed-out redirect ────────────────────────────────────────

    fn headers_with_cookie(cookie: &str) -> axum::http::HeaderMap {
        let mut h = axum::http::HeaderMap::new();
        h.insert("cookie", cookie.parse().unwrap());
        h
    }

    fn uri(path: &str) -> axum::http::Uri {
        path.parse().unwrap()
    }

    fn location(response: &axum::response::Response) -> String {
        response
            .headers()
            .get(axum::http::header::LOCATION)
            .and_then(|v| v.to_str().ok())
            .unwrap_or_default()
            .to_string()
    }

    /// A signed-out visit to a flow page is sent to /login with the page to
    /// return to, so an invitation link survives the sign-in.
    #[test]
    fn signed_out_flow_page_redirects_to_login_with_return_path() {
        let _ = krausen_core::constants::load_with_fallback();
        let response = check_auth_cookie_or_redirect(
            &axum::http::HeaderMap::new(),
            Some(&uri("/accept-invite/inv-1234")),
        )
        .expect("no cookie must redirect");
        assert_eq!(response.status(), axum::http::StatusCode::SEE_OTHER);
        assert_eq!(location(&response), "/login?redirect=/accept-invite/inv-1234");
    }

    /// Either token cookie lets the shell through: with only a refresh cookie
    /// the page refreshes the session before it boots.
    #[test]
    fn an_access_or_refresh_cookie_serves_the_page() {
        let _ = krausen_core::constants::load_with_fallback();
        for cookie in ["access_token=abc", "refresh_token=abc", "x=1; refresh_token=abc"] {
            assert!(
                check_auth_cookie_or_redirect(&headers_with_cookie(cookie), Some(&uri("/recipes")))
                    .is_none(),
                "{cookie} should be let through"
            );
        }
        let empty = check_auth_cookie_or_redirect(
            &headers_with_cookie("access_token="),
            Some(&uri("/recipes")),
        );
        assert!(empty.is_some(), "an empty cookie value is not a session");
    }

    /// A return path with unexpected characters, the root or /login itself is
    /// dropped rather than echoed into the Location header.
    #[test]
    fn unsafe_or_pointless_return_paths_redirect_to_bare_login() {
        let _ = krausen_core::constants::load_with_fallback();
        for path in ["/", "/login", "/a%0d%0ab", "/a.b", "/a;b"] {
            let response = check_auth_cookie_or_redirect(
                &axum::http::HeaderMap::new(),
                Some(&uri(path)),
            )
            .expect("no cookie must redirect");
            assert_eq!(location(&response), "/login", "path {path}");
        }
    }

    #[test]
    fn public_routes_render_without_a_cookie_and_app_routes_do_not() {
        for path in [
            "login",
            "signup",
            "signup/complete",
            "welcome",
            "unsubscribe",
            "auth/google/callback",
            "auth/recover-passkey",
            "account/recover/complete",
            "oauth-complete",
        ] {
            assert!(is_public_route(path), "{path} should be public");
        }
        for path in [
            "",
            "recipes",
            "settings/profile",
            "accept-invite/inv-1",
            "accept-ownership/t-1",
            "signupwhatever",
        ] {
            assert!(!is_public_route(path), "{path} should not be public");
        }
    }
}
